import { lstatSync, readFileSync, realpathSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { ConfigError, type configPath, type loadConfig } from "../skills/dori-mode/scripts/src/config.ts";
import {
  assertSetupFile,
  captureSetupFile,
  publishSetupFile,
  readSetupFile,
  setupPreview,
  type SetupSnapshot,
} from "../src/setup-files.ts";
import { setupOverrideKeys, setupReadback } from "../src/setup-readback.ts";
import { canonical } from "../src/update/config.ts";

type Snapshot = {
  version: 1;
  base: string;
  source: string;
  mode: "primary" | "side";
  files: SetupSnapshot[];
};
type Plan = { snapshot: SetupSnapshot; text: string | Buffer; keys: string[] };
const mapping = (value: unknown): value is Record<string, unknown> =>
  value !== null && typeof value === "object" && !Array.isArray(value);

function jsonPlan(snapshot: Snapshot): Plan {
  const file = snapshot.files[0]!;
  const saved = readSetupFile(file);
  const created = saved === undefined;
  const input = created ? join(snapshot.source, "skills/dori-mode/references/config.example.json") : file.path;
  let original: Buffer;
  try {
    original = saved ?? readFileSync(input);
  } catch {
    throw new Error(
      `Cannot read configuration input ${input}; select a complete checkout with DORI_SRC before --preview`,
    );
  }
  const decoded = original.toString("utf8");
  const config: unknown = JSON.parse(decoded);
  if (!mapping(config)) throw new Error(`Configuration must be a JSON object: ${input}`);
  const keys: string[] = [];
  if (created && snapshot.mode === "side") {
    config["stateDir"] = join(snapshot.base, "state");
    keys.push("stateDir");
  }
  if (!config["agentCommand"] || (Array.isArray(config["agentCommand"]) && config["agentCommand"][0] === "omp")) {
    const rest = Array.isArray(config["agentCommand"])
      ? config["agentCommand"].slice(1)
      : ["--dori-role", "lane", "--model", "{model}", "{prompt}"];
    // A source-home alias still uses the managed argv prefix of the physical installation.
    config["agentCommand"] = [join(dirname(file.path), "bin/omp"), ...rest];
    keys.push("agentCommand");
  }
  if (config["ompUlwPath"] !== "") {
    config["ompUlwPath"] = "";
    keys.push("ompUlwPath");
  }
  if ((created || keys.length) && !Buffer.from(decoded).equals(original))
    throw new Error(
      `Configuration rewrite would change non-UTF-8 bytes: ${input}; repair the encoding before retrying`,
    );
  return { snapshot: file, text: created || keys.length ? `${JSON.stringify(config, null, 2)}\n` : original, keys };
}

function yamlPlan(snapshot: Snapshot): Plan {
  const file = snapshot.files[1]!;
  const saved = readSetupFile(file);
  let previous: unknown = {};
  if (saved !== undefined) {
    try {
      previous = Bun.YAML.parse(new TextDecoder("utf-8", { fatal: true }).decode(saved));
    } catch {
      throw new Error(`Configuration must be valid UTF-8 YAML: ${file.path}`);
    }
  }
  const skills = mapping(previous) ? (previous["skills"] ?? {}) : undefined;
  const update = mapping(previous) ? (previous["update"] ?? {}) : undefined;
  if (!mapping(previous) || !mapping(skills) || !mapping(update))
    throw new Error(`Configuration must be a YAML mapping of mappings: ${file.path}`);
  const merged = {
    ...previous,
    skills: {
      ...skills,
      ignoredSkills: ["dori-mode"],
      customDirectories: [join(snapshot.base, "skills")],
    },
    update: { ...update, auto: false },
  };
  return {
    snapshot: file,
    text: `# Generated by scripts/install-source.sh for omp-dori omp sessions; skills paths and update.auto are managed.\n${Bun.YAML.stringify(merged, null, 2)}\n`,
    keys: ["skills.ignoredSkills", "skills.customDirectories", "update.auto"],
  };
}

function preview(plan: Plan): void {
  console.error(`SETUP_PREVIEW ${JSON.stringify(setupPreview(plan.snapshot, plan.text, plan.keys))}`);
}

const readerFailure = "Effective configuration reader is unavailable in the selected source checkout";
const readerEnvironment = [
  "DORI_HOME",
  "DORI_CONFIG",
  "DORI_AGENT_ARGV",
  "DORI_AGENT_CMD",
  "DORI_AGENT_EXECUTABLE",
  "DORI_STATE_DIR",
  "DORI_OMP_ULW_PATH",
  "DORI_LEAD_PANE",
] as const;

async function probeReader(snapshot: Snapshot, scope: string): Promise<void> {
  // This is the fixed reader beside the installed CLI, not an env- or config-supplied module reference.
  const readerPath = join(realpathSync(snapshot.source), "skills/dori-mode/scripts/src/config.ts");
  if (!lstatSync(readerPath).isFile() || realpathSync(readerPath) !== readerPath) throw new Error(readerFailure);
  const reader: { configPath: typeof configPath; loadConfig: typeof loadConfig; ConfigError: typeof ConfigError } =
    await import(pathToFileURL(readerPath).href);
  if (
    typeof reader.configPath !== "function" ||
    typeof reader.loadConfig !== "function" ||
    typeof reader.ConfigError !== "function"
  )
    throw new Error(readerFailure);
  console.log(JSON.stringify(await setupReadback(snapshot.files[0]!, scope, { reader })));
}

function sourceReadback(snapshot: Snapshot, scope: string): void {
  const env: Record<string, string> = {
    HOME: homedir(),
    PATH: process.env["PATH"] ?? "/usr/bin:/bin",
    BUN_RUNTIME_TRANSPILER_CACHE_PATH: "0",
    DORI_SETUP_SNAPSHOT: JSON.stringify(snapshot),
  };
  for (const key of readerEnvironment) {
    const value = process.env[key];
    if (value !== undefined) env[key] = value;
  }
  if (snapshot.mode === "side") {
    const base = snapshot.base;
    env["DORI_HOME"] = base;
    env["DORI_CONFIG"] = join(base, "config.json");
    env["DORI_STATE_DIR"] = join(base, "state");
    env["DORI_AGENT_ARGV"] = JSON.stringify([join(base, "bin/omp")]);
    for (const key of ["DORI_AGENT_CMD", "DORI_AGENT_EXECUTABLE", "DORI_OMP_ULW_PATH"]) delete env[key];
  }
  const child = Bun.spawnSync(
    [
      process.execPath,
      "--config=/dev/null",
      "--no-env-file",
      "--no-install",
      import.meta.path,
      "probe-readback",
      snapshot.base,
      snapshot.source,
      snapshot.mode,
    ],
    { env, stdin: "ignore", stdout: "pipe", stderr: "ignore", timeout: 30_000 },
  );
  const file = snapshot.files[0]!;
  assertSetupFile(file);
  if (child.exitCode !== 0) throw new Error(readerFailure);

  // Never forward child output verbatim. Only the redacted receipt is accepted.
  let receipt: unknown;
  try {
    receipt = JSON.parse(child.stdout.toString());
  } catch (error) {
    if (!(error instanceof SyntaxError)) throw error;
    throw new Error(readerFailure);
  }
  if (
    !mapping(receipt) ||
    receipt["path"] !== file.path ||
    receipt["sha256"] !== file.sha256 ||
    receipt["saved"] !== true ||
    receipt["scope"] !== scope ||
    typeof receipt["selectedConfig"] !== "string"
  )
    throw new Error(readerFailure);
  const result = {
    path: file.path,
    sha256: file.sha256,
    saved: true,
    scope,
    selectedConfig: receipt["selectedConfig"],
  };
  if (receipt["effective"] === "unavailable") {
    const reason = receipt["reason"];
    if (
      receipt["overridden"] !== null ||
      (reason !== "invalid-effective-configuration" &&
        reason !== "current-updater-runtime-unavailable" &&
        reason !== "configuration-reader-unavailable")
    )
      throw new Error(readerFailure);
    console.log(`SETUP_READBACK ${JSON.stringify({ ...result, effective: "unavailable", overridden: null, reason })}`);
    throw new ConfigError("Effective configuration readback is unavailable");
  }
  const effective = receipt["effective"];
  const overridden = receipt["overridden"];
  if (
    (effective !== "selected" && effective !== "shadowed") ||
    !Array.isArray(overridden) ||
    overridden.some((key: unknown) => !setupOverrideKeys.some((allowed) => key === allowed))
  )
    throw new Error(readerFailure);
  console.log(`SETUP_READBACK ${JSON.stringify({ ...result, effective, overridden })}`);
}

async function main(): Promise<void> {
  const [action, baseArg, sourceArg, mode] = process.argv.slice(2);
  if (!baseArg || !sourceArg || (mode !== "primary" && mode !== "side") || process.argv.length !== 6)
    throw new Error("Expected action, absolute installation home, source checkout and primary|side mode");
  if (!["capture", "preview", "publish-json", "publish-yaml", "readback", "probe-readback"].includes(action ?? ""))
    throw new Error("Unknown source configuration operation");
  const base = resolve(baseArg),
    source = resolve(sourceArg);
  const physicalBase = canonical(base);
  let snapshot: Snapshot;
  if (action === "capture" || action === "preview") {
    snapshot = {
      version: 1,
      base,
      source,
      mode,
      files: [
        captureSetupFile(join(physicalBase, "config.json")),
        ...(mode === "side" ? [captureSetupFile(join(physicalBase, "omp.yml"))] : []),
      ],
    };
  } else {
    const raw = process.env["DORI_SETUP_SNAPSHOT"];
    if (!raw) throw new Error("Missing private setup snapshot; rerun the source installer");
    snapshot = JSON.parse(raw) as Snapshot;
    if (
      snapshot.version !== 1 ||
      snapshot.base !== base ||
      snapshot.source !== source ||
      snapshot.mode !== mode ||
      snapshot.files.length !== (mode === "side" ? 2 : 1) ||
      snapshot.files[0]?.path !== join(physicalBase, "config.json") ||
      (mode === "side" && snapshot.files[1]?.path !== join(physicalBase, "omp.yml"))
    )
      throw new Error("Setup snapshot does not belong to this installation; rerun the source installer");
  }
  for (const file of snapshot.files) assertSetupFile(file);
  if (action === "preview") {
    const plans = mode === "side" ? [jsonPlan(snapshot), yamlPlan(snapshot)] : [jsonPlan(snapshot)];
    for (const file of snapshot.files) assertSetupFile(file);
    for (const plan of plans) preview(plan);
    console.log("SETUP_PREVIEW_ONLY no configuration, checkout, dependency or reference was changed");
    return;
  }
  if (action === "publish-json" || action === "publish-yaml") {
    if (action === "publish-yaml" && mode !== "side")
      throw new Error("Primary source setup has no managed YAML overlay");
    const plan = action === "publish-json" ? jsonPlan(snapshot) : yamlPlan(snapshot);
    preview(plan);
    for (const file of snapshot.files) assertSetupFile(file);
    const index = action === "publish-json" ? 0 : 1;
    snapshot.files[index] = publishSetupFile(plan.snapshot, plan.text);
  }
  const scope = mode === "side" ? "generated-side-wrapper" : "installer-environment";
  if (action === "probe-readback") {
    await probeReader(snapshot, scope);
    return;
  }
  if (action === "readback") {
    sourceReadback(snapshot, scope);
    if (mode === "side") {
      assertSetupFile(snapshot.files[1]!);
      console.log(
        `SETUP_READBACK ${JSON.stringify({
          path: snapshot.files[1]!.path,
          sha256: snapshot.files[1]!.sha256,
          saved: true,
          scope: "generated-native-wrapper --config",
          nativeSession: "not-started",
        })}`,
      );
    }
    return;
  }
  console.log(JSON.stringify(snapshot));
}

try {
  await main();
} catch (error) {
  const reason =
    error instanceof SyntaxError
      ? "Invalid configuration JSON; inspect the selected file"
      : error instanceof ConfigError
        ? "Invalid effective Dori configuration; inspect the selected file"
        : error instanceof Error
          ? error.message
          : String(error);
  console.error(`Configuration setup held: ${reason}`);
  process.exitCode = 1;
}
