import { splitForDiscord } from "../skills/dori-mode/scripts/src/messenger/split.ts";

export type NativeDelivery = { readonly prompt: string; readonly after: string | null };

const record = (value: unknown): value is Record<string, unknown> => typeof value === "object" && value !== null;

function userTimestamp(message: unknown, prompt: string): number | undefined {
  if (!record(message) || message["role"] !== "user") return;
  const { content, timestamp } = message;
  if (typeof timestamp !== "number" || !Number.isFinite(timestamp)) return;
  if (content === prompt) return timestamp;
  if (!Array.isArray(content) || content.length !== 1) return;
  const block: unknown = content[0];
  if (record(block) && block["type"] === "text" && block["text"] === prompt) return timestamp;
}

/** The native journal wraps actual user messages in branch-local message entries with their own IDs. */
export function nativeDiscordReceipt(branch: readonly unknown[], delivery: NativeDelivery) {
  const { after, prompt } = delivery;
  const baseline = after === null ? -1 : branch.findIndex((entry) => record(entry) && entry["id"] === after);
  if (after !== null && baseline < 0) return;
  let receipt: { readonly index: number; readonly timestamp: number } | undefined;
  for (let index = baseline + 1; index < branch.length; index++) {
    const entry = branch[index];
    if (!record(entry) || entry["type"] !== "message" || typeof entry["id"] !== "string") continue;
    const timestamp = userTimestamp(entry["message"], prompt);
    if (timestamp === undefined) continue;
    if (receipt) return;
    receipt = { index, timestamp };
  }
  return receipt;
}

const isReplyContext = (role: unknown): boolean =>
  role === "assistant" || role === "toolResult" || role === "developer";

const isCommentary = (signature: unknown): boolean => {
  // OpenAI Responses uses a JSON text signature for phase; legacy signatures are plain IDs.
  if (typeof signature !== "string" || !signature.startsWith("{")) return false;
  try {
    const decoded: unknown = JSON.parse(signature);
    return record(decoded) && decoded["phase"] === "commentary";
  } catch (error) {
    if (error instanceof SyntaxError) return true;
    throw error;
  }
};

type ReplySettle =
  | { readonly kind: "continued"; readonly through: number }
  | { readonly kind: "discard" }
  | { readonly kind: "answer"; readonly text: string; readonly timestamp: number };

/** OMP reports the active transcript, not only the messages generated by this run. */
function finalDiscordLaneReply(
  event: unknown,
  delivery: NativeDelivery,
  through: number,
  nativeTimestamp: number,
): ReplySettle | undefined {
  if (!record(event) || !Array.isArray(event["messages"])) return;
  const messages: readonly unknown[] = event["messages"];
  const continuing = event["willContinue"] === true;
  let anchor = false;
  let superseded = false;
  let lastAssistant = through;
  for (let i = messages.length - 1; i >= 0; i--) {
    const message = messages[i];
    if (!record(message)) continue;
    const role = message["role"];
    if (userTimestamp(message, delivery.prompt) === nativeTimestamp) {
      anchor = true;
      break;
    }
    // Tool output and its passive developer context belong to the same request. Other inputs may start their own work.
    if (!isReplyContext(role)) superseded = true;
    const timestamp = message["timestamp"];
    if (continuing && role === "assistant" && typeof timestamp === "number" && Number.isFinite(timestamp))
      lastAssistant = Math.max(lastAssistant, timestamp);
  }
  if (!anchor) return;
  if (superseded) return { kind: "discard" };
  if (continuing) return lastAssistant > through ? { kind: "continued", through: lastAssistant } : undefined;
  const answer = publicAnswer(messages.at(-1));
  return answer && answer.timestamp > through ? answer : { kind: "discard" };
}

function publicAnswer(final: unknown): Extract<ReplySettle, { kind: "answer" }> | undefined {
  if (
    !record(final) ||
    final["role"] !== "assistant" ||
    final["stopReason"] !== "stop" ||
    typeof final["timestamp"] !== "number" ||
    !Number.isFinite(final["timestamp"]) ||
    !Array.isArray(final["content"])
  )
    return;
  const content: readonly unknown[] = final["content"];
  const parts: string[] = [];
  for (const block of content) {
    if (!record(block)) continue;
    if (block["type"] === "toolCall") return;
    if (block["type"] === "text" && typeof block["text"] === "string" && !isCommentary(block["textSignature"]))
      parts.push(block["text"]);
  }
  const text = parts.join("\n").trim();
  return text ? { kind: "answer", text, timestamp: final["timestamp"] } : undefined;
}

type PendingReply = {
  readonly delivery: NativeDelivery;
  readonly enqueue: (parts: readonly string[]) => void;
  started: boolean;
  through: number;
  continuing: boolean;
  prepared: boolean;
  accepted: boolean;
  answer?: Extract<ReplySettle, { kind: "answer" }>;
};

/** An in-memory attempt cannot be re-created from a saved transcript. */
export class DiscordLaneReplies {
  private pending?: PendingReply;

  constructor(private readonly branch: () => readonly unknown[]) {}

  armNative(prompt: string, enqueue: PendingReply["enqueue"]): NativeDelivery | undefined {
    const branch = this.branch();
    const leaf = branch.at(-1);
    const after = record(leaf) && typeof leaf["id"] === "string" ? leaf["id"] : null;
    if (branch.length !== 0 && after === null) return;
    const delivery: NativeDelivery = { prompt, after };
    this.pending = {
      delivery,
      enqueue,
      started: false,
      through: 0,
      continuing: false,
      prepared: false,
      accepted: false,
    };
    return delivery;
  }

  prepareNative(delivery: NativeDelivery): void {
    if (this.pending?.delivery === delivery) this.pending.prepared = true;
  }

  acceptNative(delivery: NativeDelivery): void {
    const pending = this.pending;
    if (pending?.delivery !== delivery) return;
    pending.accepted = true;
    if (pending.answer) this.publish(pending, pending.answer);
  }

  discardNative(delivery: NativeDelivery): void {
    if (this.pending?.delivery === delivery) this.pending = undefined;
  }

  agentStart(): void {
    const pending = this.pending;
    if (!pending?.prepared || pending.answer) return;
    // Native start notifications may run after the corresponding input has already been persisted.
    if (!pending.started) {
      pending.started = true;
      return;
    }
    if (!nativeDiscordReceipt(this.branch(), pending.delivery)) return;
    if (pending.continuing) pending.continuing = false;
    else this.pending = undefined;
  }

  agentEnd(event: unknown): void {
    const pending = this.pending;
    if (!pending?.started || !pending.prepared || pending.answer) return;
    const receipt = nativeDiscordReceipt(this.branch(), pending.delivery);
    if (!receipt) return;
    const result = finalDiscordLaneReply(event, pending.delivery, pending.through, receipt.timestamp);
    if (!result) return;
    switch (result.kind) {
      case "continued":
        pending.through = result.through;
        pending.continuing = true;
        return;
      case "answer":
        if (pending.accepted) this.publish(pending, result);
        else pending.answer = result;
        return;
      case "discard":
        break;
    }
    this.pending = undefined;
  }

  private publish(pending: PendingReply, answer: Extract<ReplySettle, { kind: "answer" }>): void {
    this.pending = undefined;
    const branch = this.branch();
    const receipt = nativeDiscordReceipt(branch, pending.delivery);
    if (!receipt) return;
    let final: unknown;
    for (let index = receipt.index + 1; index < branch.length; index++) {
      const entry = branch[index];
      if (!record(entry)) continue;
      if (entry["type"] === "custom_message") return;
      if (entry["type"] !== "message") continue;
      const message = entry["message"];
      if (!record(message) || !isReplyContext(message["role"])) return;
      final = message;
    }
    const persisted = publicAnswer(final);
    if (!persisted || persisted.timestamp !== answer.timestamp || persisted.text !== answer.text) return;
    pending.enqueue(splitForDiscord(answer.text));
  }
}
